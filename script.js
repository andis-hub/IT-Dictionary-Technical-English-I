        // GENERATE ALPHABET BUTTONS

        const alphabetContainer = document.getElementById("alphabet");

        const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";

        for (const letter of letters) {

            const button = document.createElement("button");

            button.textContent = letter;
            button.type = "button";

            button.addEventListener("click", function () {
                showLetter(letter);
            });

            alphabetContainer.appendChild(button);

        }


        // DISPLAY WORDS BY LETTER

        function showLetter(letter) {

            const content = document.getElementById("dictionary-content");

            const words = dictionary[letter];

            if (!words || words.length === 0) {

                content.innerHTML = `
                <h3>${letter}</h3>
                <p>No words available for this letter.</p>
            `;

                return;
            }

            let html = `<h3>Letter ${letter}</h3>`;

            words.forEach(function (item) {

                html += `
                <div class="word-block">

                    <h3>${item.word}</h3>

                    <p>
                        <strong>Definition:</strong>
                        ${item.definition}
                    </p>

                    <p>
                        <strong>Translation:</strong>
                        ${item.translation}
                    </p>

                    <h4>Examples:</h4>

                    <ul>
            `;

                item.examples.forEach(function (example) {

                    html += `<li>${example}</li>`;

                });

                html += `
                    </ul>

                </div>
            `;

            });

            content.innerHTML = html;

        }


        // CHANGE MAIN SECTION

        function showTab(tabId) {

            const sections = document.querySelectorAll(".tab-content");

            sections.forEach(function (section) {

                section.classList.remove("active");

            });

            const selectedSection = document.getElementById(tabId);

            if (selectedSection) {

                selectedSection.classList.add("active");

            }

            window.scrollTo({
                top: 0,
                behavior: "smooth"
            });

        }


        // SHOW LETTER A BY DEFAULT

        showLetter("A");